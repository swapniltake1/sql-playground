Topic: Manufacturing Lot Traceability, Quality Yield & Recall Readiness
Dialect: PostgreSQL 14+

Run this file in a disposable PostgreSQL database. It recreates only the
dedicated mfg_trace_practice schema.

Scenario
--------
A manufacturer builds precision valve assemblies from semi-finished
subassemblies and raw-material lots. MES messages can be replayed or corrected.
Quality inspections can also be revised or voided. Operations needs reliable
lot genealogy, first-pass yield, defect Pareto, production variance, cycle-time
metrics, and a defensible answer to "which finished lots used this component?"

Learning goals
--------------
* Canonicalize replayed and corrected source events deterministically.
* Preserve the distinction between raw landing data and trusted canonical data.
* Traverse multi-level genealogy without infinite recursion.
* Aggregate at the correct grain before joining.
* Build auditable quality and release-readiness controls.
===============================================================================
*/

DROP SCHEMA IF EXISTS mfg_trace_practice CASCADE;
CREATE SCHEMA mfg_trace_practice;

CREATE TABLE mfg_trace_practice.products (
    product_id      text PRIMARY KEY,
    sku             text NOT NULL UNIQUE,
    product_name    text NOT NULL,
    product_type    text NOT NULL CHECK (product_type IN ('FINISHED', 'SEMI', 'RAW'))
);

CREATE TABLE mfg_trace_practice.work_orders (
    work_order_id   text PRIMARY KEY,
    product_id      text NOT NULL REFERENCES mfg_trace_practice.products(product_id),
    site_id         text NOT NULL,
    planned_qty     numeric(14,3) NOT NULL CHECK (planned_qty > 0),
    planned_start   timestamptz NOT NULL,
    planned_finish  timestamptz NOT NULL
);

CREATE TABLE mfg_trace_practice.production_lots (
    lot_id          text PRIMARY KEY,
    lot_code        text NOT NULL UNIQUE,
    work_order_id   text REFERENCES mfg_trace_practice.work_orders(work_order_id),
    product_id      text NOT NULL REFERENCES mfg_trace_practice.products(product_id),
    site_id         text NOT NULL,
    lot_type        text NOT NULL CHECK (lot_type IN ('FINISHED', 'SEMI', 'RAW')),
    qty_started     numeric(14,3) NOT NULL CHECK (qty_started >= 0),
    qty_completed   numeric(14,3) NOT NULL CHECK (qty_completed >= 0),
    started_at      timestamptz NOT NULL,
    completed_at    timestamptz,
    lot_status      text NOT NULL CHECK (lot_status IN ('CREATED', 'IN_PROCESS', 'HOLD', 'RELEASED', 'CLOSED')),
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);

-- Raw MES landing table: deliberately no foreign keys so malformed source
-- references remain observable instead of being rejected at ingestion time.
CREATE TABLE mfg_trace_practice.genealogy_event_landing (
    event_row_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system               text NOT NULL,
    source_event_id             text NOT NULL,
    event_revision              integer NOT NULL CHECK (event_revision > 0),
    received_at                 timestamptz NOT NULL,
    parent_lot_id               text NOT NULL,
    component_lot_id            text NOT NULL,
    component_qty_per_parent_unit numeric(14,6) NOT NULL,
    consumed_at                 timestamptz NOT NULL,
    is_void                     boolean NOT NULL DEFAULT false
);

-- One logical inspection can arrive more than once and can be corrected or
-- voided by a later source revision.
CREATE TABLE mfg_trace_practice.quality_inspection_landing (
    inspection_row_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system       text NOT NULL,
    inspection_event_id text NOT NULL,
    event_revision      integer NOT NULL CHECK (event_revision > 0),
    received_at         timestamptz NOT NULL,
    lot_id              text NOT NULL,
    operation_code      text NOT NULL,
    attempt_no          integer NOT NULL CHECK (attempt_no > 0),
    inspected_qty       numeric(14,3) NOT NULL,
    accepted_qty        numeric(14,3) NOT NULL,
    defect_qty          numeric(14,3) NOT NULL,
    defect_code         text NOT NULL,
    inspected_at        timestamptz NOT NULL,
    is_void             boolean NOT NULL DEFAULT false
);

