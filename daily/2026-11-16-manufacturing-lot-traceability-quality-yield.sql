-- Canonical views keep landing immutable and apply latest-revision semantics.
-- A latest void revision removes the logical event from the trusted view.
CREATE OR REPLACE VIEW mfg_trace_practice.canonical_genealogy_edges AS
WITH ranked AS (
    SELECT g.*,
           ROW_NUMBER() OVER (
               PARTITION BY source_system, source_event_id
               ORDER BY event_revision DESC, received_at DESC, event_row_id DESC
           ) AS rn
    FROM mfg_trace_practice.genealogy_event_landing AS g
)
SELECT event_row_id, source_system, source_event_id, event_revision,
       received_at, parent_lot_id, component_lot_id,
       component_qty_per_parent_unit, consumed_at
FROM ranked
WHERE rn = 1
  AND NOT is_void;

CREATE OR REPLACE VIEW mfg_trace_practice.canonical_quality_inspections AS
WITH ranked AS (
    SELECT q.*,
           ROW_NUMBER() OVER (
               PARTITION BY source_system, inspection_event_id
               ORDER BY event_revision DESC, received_at DESC, inspection_row_id DESC
           ) AS rn
    FROM mfg_trace_practice.quality_inspection_landing AS q
)
SELECT inspection_row_id, source_system, inspection_event_id, event_revision,
       received_at, lot_id, operation_code, attempt_no, inspected_qty,
       accepted_qty, defect_qty, defect_code, inspected_at
FROM ranked
WHERE rn = 1
  AND NOT is_void;

/*
===============================================================================
PROBLEM 1 — Canonicalize genealogy events
===============================================================================
Problem:
Return one trusted row per source-system/source-event key. The latest revision
wins; receipt time and landing identity provide deterministic tie-breaks.
A latest void revision must suppress the event.

Optimized solution:
*/
SELECT source_system, source_event_id, event_revision,
       parent_lot_id, component_lot_id,
       component_qty_per_parent_unit, consumed_at
FROM mfg_trace_practice.canonical_genealogy_edges
ORDER BY source_system, source_event_id;

/*
Why this shape:
* ROW_NUMBER partitions by the true logical event key, not by lot pair.
* Revision is the primary ordering key; receipt timestamp is only a tie-break.
* The canonical view is reusable, so downstream questions do not each invent
  slightly different replay/correction rules.
* Do not delete landing duplicates: they are useful for source-delivery audits.

Spot checks:
* G-001 must show revision 2 and quantity 1.000000.
* G-003 must appear once despite its same-revision replay.
* G-010, G-011, and G-012 remain visible for quality controls.
*/

/*
===============================================================================
PROBLEM 2 — First-pass yield by site and finished product
===============================================================================
Problem:
Calculate first-pass yield using only canonical FINAL inspections where
attempt_no = 1. Rework attempts must not inflate the first-pass denominator.

Optimized solution:
*/
WITH first_pass AS (
    SELECT lot_id,
           SUM(inspected_qty) AS inspected_units,
           SUM(accepted_qty) AS accepted_units,
           SUM(defect_qty) AS defect_units
    FROM mfg_trace_practice.canonical_quality_inspections
    WHERE operation_code = 'FINAL'
      AND attempt_no = 1
    GROUP BY lot_id
)
SELECT l.site_id,
       p.sku,
       p.product_name,
       SUM(fp.inspected_units) AS inspected_units,
       SUM(fp.accepted_units) AS accepted_units,
       SUM(fp.defect_units) AS defect_units,
       ROUND(
           100.0 * SUM(fp.accepted_units)
           / NULLIF(SUM(fp.inspected_units), 0),
           2
       ) AS first_pass_yield_pct
FROM first_pass AS fp
JOIN mfg_trace_practice.production_lots AS l
  ON l.lot_id = fp.lot_id
JOIN mfg_trace_practice.products AS p
  ON p.product_id = l.product_id
WHERE l.lot_type = 'FINISHED'
GROUP BY l.site_id, p.sku, p.product_name
ORDER BY l.site_id, p.sku;

/*
Why this shape:
* Reduce inspection rows to one row per lot before joining lot/product
  dimensions. This prevents a one-to-many join from multiplying quantities.
* Filter operation and attempt before aggregation.
* NULLIF protects zero-denominator batches.
* QI-002 is a rework attempt and is intentionally excluded from first-pass yield.

Expected sample values:
* PLANT-A: 96 / 100 = 96.00%.
* PLANT-B: 78 / 80 = 97.50%.
*/

/*
===============================================================================
PROBLEM 3 — Defect Pareto and cumulative contribution
===============================================================================
Problem:
Rank defect categories by observed defect quantity and calculate each
category's share plus cumulative share. Exclude voided inspections and
malformed/orphan records.

Optimized solution:
*/
WITH defect_totals AS (
    SELECT q.defect_code,
           SUM(q.defect_qty) AS defect_units
    FROM mfg_trace_practice.canonical_quality_inspections AS q
    JOIN mfg_trace_practice.production_lots AS l
      ON l.lot_id = q.lot_id
    WHERE q.defect_qty > 0
    GROUP BY q.defect_code
),
pareto AS (
    SELECT defect_code,
           defect_units,
           SUM(defect_units) OVER () AS total_defects,
           SUM(defect_units) OVER (
               ORDER BY defect_units DESC, defect_code
               ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
           ) AS cumulative_defects
    FROM defect_totals
)
SELECT defect_code,
       defect_units,
       ROUND(100.0 * defect_units / NULLIF(total_defects, 0), 2) AS share_pct,
       ROUND(100.0 * cumulative_defects / NULLIF(total_defects, 0), 2) AS cumulative_share_pct
FROM pareto
ORDER BY defect_units DESC, defect_code;

/*
Why this shape:
* Aggregate once at defect-code grain, then use window functions for shares.
* The explicit ROWS frame and defect_code tie-break make the cumulative
  calculation deterministic.
* Joining production_lots removes orphan QI-009 from business reporting.
* These are observed defect counts, not necessarily unique rejected units;
  production definitions must clarify whether multiple defects can occur on
  the same physical unit.
*/

/*
===============================================================================
PROBLEM 4 — Multi-level component quantity explosion
===============================================================================
Problem:
For one finished lot, calculate raw-material requirements per one finished
unit across all genealogy levels. Stop recursive expansion at a detected
cycle and return leaf component lots only.

Optimized solution:
*/
WITH RECURSIVE walk AS (
    SELECT 'LOT-F100'::text AS root_lot_id,
           'LOT-F100'::text AS current_lot_id,
           1.000000::numeric AS qty_per_root_unit,
           0 AS depth,
           ARRAY['LOT-F100']::text[] AS path,
           false AS cycle_found

    UNION ALL

    SELECT w.root_lot_id,
           e.component_lot_id,
           w.qty_per_root_unit * e.component_qty_per_parent_unit,
           w.depth + 1,
           w.path || e.component_lot_id,
           e.component_lot_id = ANY(w.path)
    FROM walk AS w
    JOIN mfg_trace_practice.canonical_genealogy_edges AS e
      ON e.parent_lot_id = w.current_lot_id
    JOIN mfg_trace_practice.production_lots AS child
      ON child.lot_id = e.component_lot_id
    WHERE NOT w.cycle_found
      AND w.depth < 20
      AND e.component_qty_per_parent_unit > 0
)
SELECT w.current_lot_id AS component_lot_id,
       l.lot_code,
       l.lot_type,
       w.qty_per_root_unit,
       w.depth
FROM walk AS w
JOIN mfg_trace_practice.production_lots AS l
  ON l.lot_id = w.current_lot_id
WHERE w.depth > 0
  AND NOT w.cycle_found
  AND NOT EXISTS (
      SELECT 1
      FROM mfg_trace_practice.canonical_genealogy_edges AS e
      WHERE e.parent_lot_id = w.current_lot_id
        AND e.component_qty_per_parent_unit > 0
        AND EXISTS (
            SELECT 1
            FROM mfg_trace_practice.production_lots AS child
            WHERE child.lot_id = e.component_lot_id
        )
  )
ORDER BY l.lot_type, l.lot_code;

/*
Why this shape:
* The recursive state carries the multiplier, path, and depth.
* Multipliers compose across levels: 1 finished unit x 1 subassembly x 2
  steel blanks = 2 steel blanks per finished unit.
* The path guard prevents infinite loops; the depth cap is a second safety
  boundary, not a substitute for a cycle-quality control.
* Positive quantity and valid child-lot checks keep malformed landing edges
  out of the material explosion.
* For very deep/high-volume BOMs, consider a maintained closure table or
  precomputed genealogy snapshot rather than repeatedly traversing raw edges.
*/

/*
===============================================================================
PROBLEM 5 — Forward traceability: component lot to affected finished lots
===============================================================================
Problem:
A supplier reports a quality concern for LOT-R100. Find every finished lot
that consumed it, directly or through intermediate subassemblies.

Optimized solution:
*/
WITH RECURSIVE affected AS (
    SELECT 'LOT-R100'::text AS source_component_lot,
           'LOT-R100'::text AS current_lot_id,
           ARRAY['LOT-R100']::text[] AS path,
           0 AS depth,
           false AS cycle_found

    UNION ALL

    SELECT a.source_component_lot,
           e.parent_lot_id,
           a.path || e.parent_lot_id,
           a.depth + 1,
           e.parent_lot_id = ANY(a.path)
    FROM affected AS a
    JOIN mfg_trace_practice.canonical_genealogy_edges AS e
      ON e.component_lot_id = a.current_lot_id
    JOIN mfg_trace_practice.production_lots AS parent_lot
      ON parent_lot.lot_id = e.parent_lot_id
    WHERE NOT a.cycle_found
      AND a.depth < 20
      AND e.component_qty_per_parent_unit > 0
)
SELECT DISTINCT l.lot_id,
       l.lot_code,
       l.site_id,
       l.lot_status
FROM affected AS a
JOIN mfg_trace_practice.production_lots AS l
  ON l.lot_id = a.current_lot_id
WHERE l.lot_type = 'FINISHED'
  AND NOT a.cycle_found
ORDER BY l.site_id, l.lot_code;

/*
Why this shape:
* This is the reverse traversal of Q4: component_lot_id points to its parent.
* DISTINCT removes multiple valid paths to the same finished lot.
* Parent existence and positive quantity are checked before recursion.
* In a recall workflow, persist the trace result with the source event,
  as-of timestamp, and genealogy version used for the investigation.
*/

/*
===============================================================================
PROBLEM 6 — Landing-data quality exceptions
===============================================================================
Problem:
Return canonical genealogy and inspection rows with missing references,
self-links, non-positive quantities, or impossible inspection arithmetic.

Optimized solution:
*/
WITH genealogy_exceptions AS (
    SELECT 'GENEALOGY'::text AS source_area,
           e.source_system,
           e.source_event_id AS source_key,
           e.parent_lot_id AS lot_id,
           CASE
             WHEN parent_lot.lot_id IS NULL THEN 'UNKNOWN_PARENT_LOT'
             WHEN child_lot.lot_id IS NULL THEN 'UNKNOWN_COMPONENT_LOT'
             WHEN e.parent_lot_id = e.component_lot_id THEN 'SELF_REFERENCE'
             WHEN e.component_qty_per_parent_unit <= 0 THEN 'NON_POSITIVE_COMPONENT_QTY'
           END AS exception_code
    FROM mfg_trace_practice.canonical_genealogy_edges AS e
    LEFT JOIN mfg_trace_practice.production_lots AS parent_lot
      ON parent_lot.lot_id = e.parent_lot_id
    LEFT JOIN mfg_trace_practice.production_lots AS child_lot
      ON child_lot.lot_id = e.component_lot_id
    WHERE parent_lot.lot_id IS NULL
       OR child_lot.lot_id IS NULL
       OR e.parent_lot_id = e.component_lot_id
       OR e.component_qty_per_parent_unit <= 0
),
inspection_exceptions AS (
    SELECT 'QUALITY'::text AS source_area,
           q.source_system,
           q.inspection_event_id AS source_key,
           q.lot_id,
           CASE
             WHEN l.lot_id IS NULL THEN 'UNKNOWN_INSPECTION_LOT'
             WHEN q.inspected_qty <= 0 THEN 'NON_POSITIVE_INSPECTED_QTY'
             WHEN q.accepted_qty < 0 OR q.accepted_qty > q.inspected_qty
               THEN 'ACCEPTED_QTY_OUT_OF_RANGE'
             WHEN q.defect_qty < 0 THEN 'NEGATIVE_DEFECT_QTY'
             WHEN q.accepted_qty + q.defect_qty <> q.inspected_qty
               THEN 'INSPECTION_QTY_DOES_NOT_RECONCILE'
           END AS exception_code
    FROM mfg_trace_practice.canonical_quality_inspections AS q
    LEFT JOIN mfg_trace_practice.production_lots AS l
      ON l.lot_id = q.lot_id
    WHERE l.lot_id IS NULL
       OR q.inspected_qty <= 0
       OR q.accepted_qty < 0
       OR q.accepted_qty > q.inspected_qty
       OR q.defect_qty < 0
       OR q.accepted_qty + q.defect_qty <> q.inspected_qty
)
SELECT *
FROM genealogy_exceptions
UNION ALL
SELECT *
FROM inspection_exceptions
ORDER BY source_area, source_key;

/*
Why this shape:
* LEFT JOIN plus IS NULL is an explicit anti-join for unknown dimension keys.
* UNION ALL preserves separate control failures; UNION would add an unnecessary
  distinct/sort step and could hide repeated exception evidence.
* The landing tables intentionally have no foreign keys: ingestion should
  preserve bad source records for quarantine and remediation.
*/

/*
===============================================================================
PROBLEM 7 — Work-order plan attainment and shortfall
===============================================================================
Problem:
Compare planned quantity with completed finished-lot quantity by work order.
Show shortfall and attainment percentage without multiplying the order plan
by the number of lots.

Optimized solution:
*/
WITH completed_by_order AS (
    SELECT work_order_id,
           SUM(qty_completed) AS completed_qty,
           COUNT(*) AS finished_lot_count
    FROM mfg_trace_practice.production_lots
    WHERE work_order_id IS NOT NULL
      AND lot_type = 'FINISHED'
    GROUP BY work_order_id
)
SELECT wo.work_order_id,
       wo.site_id,
       p.sku,
       wo.planned_qty,
       COALESCE(c.completed_qty, 0) AS completed_qty,
       wo.planned_qty - COALESCE(c.completed_qty, 0) AS shortfall_qty,
       ROUND(
           100.0 * COALESCE(c.completed_qty, 0) / NULLIF(wo.planned_qty, 0),
           2
       ) AS attainment_pct,
       COALESCE(c.finished_lot_count, 0) AS finished_lot_count
FROM mfg_trace_practice.work_orders AS wo
JOIN mfg_trace_practice.products AS p
  ON p.product_id = wo.product_id
LEFT JOIN completed_by_order AS c
  ON c.work_order_id = wo.work_order_id
ORDER BY wo.site_id, wo.work_order_id;

/*
Why this shape:
* Aggregate lots to one row per work order before joining the order header.
* This avoids a classic one-to-many fanout that would duplicate planned_qty.
* COALESCE retains work orders with no completed lots.
* For partial production, distinguish completed quantity from released/accepted
  quantity; the latter should be sourced from an approved quality disposition.
*/

/*
===============================================================================
PROBLEM 8 — Manufacturing cycle-time distribution
===============================================================================
Problem:
Calculate average and P95 elapsed production hours by site and product.
Only completed lots are included.

Optimized solution:
*/
SELECT l.site_id,
       p.sku,
       COUNT(*) AS completed_lot_count,
       ROUND(AVG(EXTRACT(EPOCH FROM (l.completed_at - l.started_at)) / 3600.0)::numeric, 2)
           AS avg_cycle_hours,
       ROUND(
           percentile_cont(0.95) WITHIN GROUP (
               ORDER BY EXTRACT(EPOCH FROM (l.completed_at - l.started_at)) / 3600.0
           )::numeric,
           2
       ) AS p95_cycle_hours
FROM mfg_trace_practice.production_lots AS l
JOIN mfg_trace_practice.products AS p
  ON p.product_id = l.product_id
WHERE l.completed_at IS NOT NULL
  AND l.lot_type = 'FINISHED'
GROUP BY l.site_id, p.sku
ORDER BY l.site_id, p.sku;

/*
Why this shape:
* Filter incomplete lots before computing elapsed durations.
* Compute percentiles over the lot-level grain, not inspection or genealogy
  rows, so each lot contributes exactly once.
* percentile_cont is an ordered-set aggregate and may sort within each group;
  for large recurring reports, consider storing daily/site/product summaries.
*/

/*
===============================================================================
PROBLEM 9 — Detect cycles in canonical lot genealogy
===============================================================================
Problem:
Find directed cycles in the active genealogy graph. A cycle means a lot is
eventually declared as its own ancestor and can make recursive traceability
unreliable.

Optimized solution:
*/
WITH RECURSIVE valid_edges AS (
    SELECT e.parent_lot_id, e.component_lot_id
    FROM mfg_trace_practice.canonical_genealogy_edges AS e
    JOIN mfg_trace_practice.production_lots AS p
      ON p.lot_id = e.parent_lot_id
    JOIN mfg_trace_practice.production_lots AS c
      ON c.lot_id = e.component_lot_id
    WHERE e.component_qty_per_parent_unit > 0
      AND e.parent_lot_id <> e.component_lot_id
),
walk AS (
    SELECT DISTINCT parent_lot_id AS start_lot_id,
           parent_lot_id AS current_lot_id,
           ARRAY[parent_lot_id]::text[] AS path,
           false AS cycle_found,
           0 AS depth
    FROM valid_edges

    UNION ALL

    SELECT w.start_lot_id,
           e.component_lot_id,
           w.path || e.component_lot_id,
           e.component_lot_id = ANY(w.path),
           w.depth + 1
    FROM walk AS w
    JOIN valid_edges AS e
      ON e.parent_lot_id = w.current_lot_id
    WHERE NOT w.cycle_found
      AND w.depth < 20
)
SELECT DISTINCT start_lot_id,
       array_to_string(path, ' -> ') AS cycle_path
FROM walk
WHERE cycle_found
ORDER BY start_lot_id;

/*
Why this shape:
* The recursive path array provides an explicit visited-node test.
* The query emits the first repeated node and stops expanding that branch.
* The depth cap protects the diagnostic query from unexpectedly deep graphs.
* For large graphs, use a graph-specific validation process or a maintained
  transitive-closure table; recursive path arrays can become memory-intensive.
*/

/*
===============================================================================
PROBLEM 10 — Finished-lot release-readiness gate
===============================================================================
Problem:
Produce an explainable screening result for each finished lot. Existing holds,
first-pass final defects, invalid direct genealogy edges, and cycles prevent
automatic readiness. This is a practice control, not a substitute for a
validated quality-management-system release procedure.

Optimized solution:
*/
WITH first_pass_quality AS (
    SELECT lot_id,
           SUM(defect_qty) AS first_pass_defects
    FROM mfg_trace_practice.canonical_quality_inspections
    WHERE operation_code = 'FINAL'
      AND attempt_no = 1
    GROUP BY lot_id
),
valid_edges AS (
    SELECT e.parent_lot_id, e.component_lot_id
    FROM mfg_trace_practice.canonical_genealogy_edges AS e
    JOIN mfg_trace_practice.production_lots AS p
      ON p.lot_id = e.parent_lot_id
    JOIN mfg_trace_practice.production_lots AS c
      ON c.lot_id = e.component_lot_id
    WHERE e.component_qty_per_parent_unit > 0
      AND e.parent_lot_id <> e.component_lot_id
),
cycle_walk AS (
    SELECT DISTINCT parent_lot_id AS start_lot_id,
           parent_lot_id AS current_lot_id,
           ARRAY[parent_lot_id]::text[] AS path,
           false AS cycle_found,
           0 AS depth
    FROM valid_edges

    UNION ALL

    SELECT w.start_lot_id,
           e.component_lot_id,
           w.path || e.component_lot_id,
           e.component_lot_id = ANY(w.path),
           w.depth + 1
    FROM cycle_walk AS w
    JOIN valid_edges AS e
      ON e.parent_lot_id = w.current_lot_id
    WHERE NOT w.cycle_found
      AND w.depth < 20
),
cycle_starts AS (
    SELECT DISTINCT start_lot_id
    FROM cycle_walk
    WHERE cycle_found
)
SELECT l.lot_id,
       l.lot_code,
       l.site_id,
       l.lot_status,
       COALESCE(q.first_pass_defects, 0) AS first_pass_defects,
       CASE
         WHEN l.lot_status = 'HOLD' THEN 'HOLD_EXISTING_STATUS'
         WHEN COALESCE(q.first_pass_defects, 0) > 0 THEN 'QUALITY_REVIEW'
         WHEN EXISTS (
             SELECT 1
             FROM mfg_trace_practice.canonical_genealogy_edges AS e
             LEFT JOIN mfg_trace_practice.production_lots AS c
               ON c.lot_id = e.component_lot_id
             WHERE e.parent_lot_id = l.lot_id
               AND (c.lot_id IS NULL OR e.component_qty_per_parent_unit <= 0)
         ) THEN 'GENEALOGY_DATA_REVIEW'
         WHEN EXISTS (
             SELECT 1
             FROM cycle_starts AS cs
             WHERE cs.start_lot_id = l.lot_id
         ) THEN 'GENEALOGY_CYCLE_REVIEW'
         ELSE 'ELIGIBLE_FOR_APPROVED_RELEASE_WORKFLOW'
       END AS release_screen
FROM mfg_trace_practice.production_lots AS l
LEFT JOIN first_pass_quality AS q
  ON q.lot_id = l.lot_id
WHERE l.lot_type = 'FINISHED'
ORDER BY l.site_id, l.lot_code;

/*
Why this shape:
* Quality is pre-aggregated to one row per lot before the release screen.
* EXISTS checks are semi-joins: they stop after the first matching exception.
* The CASE order makes the highest-priority existing hold visible first.
* A production release gate should also check calibration status, approved
  deviations, required signatures, document revisions, and customer-specific
  controls; those are outside this compact practice schema.
*/

