-- ----------------------------------------------------------------------------
-- EXPLANATIONS & PERFORMANCE NOTES
-- ----------------------------------------------------------------------------
-- 1. Atomicity: business data and outbox rows must share the same PostgreSQL
--    transaction. Do not call the broker inside a long-running DB transaction.
-- 2. Concurrency: SKIP LOCKED is appropriate for queue-like work distribution;
--    it avoids worker contention but does not promise strict FIFO completion.
-- 3. Leases: choose a lease longer than normal publish latency, renew it for
--    long work, and make lease ownership part of every ack/retry predicate.
-- 4. Delivery: a crash after broker acceptance but before published_at commits
--    causes a duplicate publish. Consumers must use an inbox/unique event key.
-- 5. Ordering: aggregate_version supports stale-event protection. If per-order
--    ordering is required, serialize claims by aggregate or make consumers
--    buffer/reject gaps; global created_at ordering alone is not sufficient.
-- 6. Indexes: partial indexes reduce hot-path size. Benchmark with realistic
--    backlog sizes; available_at filtering and created_at ordering can still
--    require heap visits or a sort depending on data distribution.
-- 7. Retention: delete in bounded batches or partition by creation month at
--    scale. Keep DLQ payloads and audit evidence according to retention policy.
-- 8. Operations: monitor oldest pending age, retry rate, lease expiry, publish
--    throughput, DLQ growth, and consumer inbox growth.
--
