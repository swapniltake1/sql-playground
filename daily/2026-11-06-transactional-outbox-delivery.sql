-- ----------------------------------------------------------------------------
-- Q1. Atomically write a business order and its outbox event.
--
-- Problem:
-- Insert order 9001 and an order.placed event. If either insert fails, neither
-- row should commit. Make the operation safe against a repeated order request.
--
-- Optimized solution:
-- Use one transaction and INSERT ... RETURNING so the event is built from the
-- row actually inserted. The unique aggregate/version key protects event replay.
-- ----------------------------------------------------------------------------

BEGIN;

WITH inserted_order AS (
    INSERT INTO orders (order_id, customer_id, order_total, status)
    VALUES (9001, 509, 1849.50, 'PLACED')
    ON CONFLICT (order_id) DO NOTHING
    RETURNING order_id, customer_id, order_total, status
)
INSERT INTO outbox_events (
    aggregate_type, aggregate_id, aggregate_version, event_type, payload
)
SELECT
    'order',
    order_id,
    1,
    'order.placed',
    jsonb_build_object(
        'order_id', order_id,
        'customer_id', customer_id,
        'total', order_total,
        'status', status
    )
FROM inserted_order
ON CONFLICT (aggregate_type, aggregate_id, aggregate_version) DO NOTHING;

COMMIT;

-- Expected: order 9001 and exactly one matching outbox event exist.
SELECT o.order_id, e.event_id, e.event_type, e.payload
FROM orders o
JOIN outbox_events e
  ON e.aggregate_type = 'order'
 AND e.aggregate_id = o.order_id
WHERE o.order_id = 9001;

-- Explanation:
-- Never commit the order and publish to the broker as two unrelated actions.
-- The database transaction guarantees both database writes commit or roll back.
-- The publisher is a separate process that polls committed outbox rows.

-- ----------------------------------------------------------------------------
-- Q2. Claim a bounded batch safely across concurrent publisher workers.
--
-- Problem:
-- Claim up to three ready events for worker-1. Ignore events with a live lease,
-- future retry time, published status, or dead-letter status. Recover expired
-- leases left by crashed workers.
--
-- Optimized solution:
-- FOR UPDATE SKIP LOCKED lets workers claim disjoint rows without waiting on
-- each other. The UPDATE both establishes a lease and increments attempts.
-- ----------------------------------------------------------------------------

WITH picked AS (
    SELECT event_id
    FROM outbox_events
    WHERE published_at IS NULL
      AND dead_lettered_at IS NULL
      AND available_at <= clock_timestamp()
      AND (locked_until IS NULL OR locked_until <= clock_timestamp())
    ORDER BY created_at, event_id
    FOR UPDATE SKIP LOCKED
    LIMIT 3
)
UPDATE outbox_events AS e
SET locked_by    = 'worker-1',
    locked_until = clock_timestamp() + interval '2 minutes',
    attempts     = e.attempts + 1
FROM picked AS p
WHERE e.event_id = p.event_id
RETURNING e.event_id, e.event_type, e.attempts, e.locked_until;

-- Expected seed selection: event IDs 2, 3, and 4.
-- Event 4 is reclaimable because its previous worker lease has expired.
-- Event 5 and event 6 are not ready because available_at is in the future.

-- ----------------------------------------------------------------------------
-- Q3. Acknowledge successful publication only for the owning worker.
--
-- Problem:
-- Simulate worker-1 successfully publishing its oldest claimed event. Do not
-- allow a different worker to acknowledge a lease it does not own.
--
-- Optimized solution:
-- Update by the indexed primary key selected from the worker's own live lease.
-- In production, acknowledge only after the broker confirms durable acceptance.
-- ----------------------------------------------------------------------------

WITH next_event AS (
    SELECT event_id
    FROM outbox_events
    WHERE locked_by = 'worker-1'
      AND locked_until > clock_timestamp()
      AND published_at IS NULL
    ORDER BY created_at, event_id
    LIMIT 1
)
UPDATE outbox_events AS e
SET published_at = clock_timestamp(),
    locked_by = NULL,
    locked_until = NULL,
    last_error = NULL
FROM next_event AS n
WHERE e.event_id = n.event_id
  AND e.locked_by = 'worker-1'
RETURNING e.event_id, e.published_at;

-- Expected: event 2 is acknowledged. Events 3 and 4 remain leased.

-- ----------------------------------------------------------------------------
-- Q4. Schedule retry with capped exponential backoff.
--
-- Problem:
-- Simulate broker failures for the remaining worker-1 events. Release their
-- leases and schedule the next attempt. Cap the delay at one hour.
--
-- Optimized solution:
-- Calculate backoff from the incremented attempts count, update only this
-- worker's outstanding leases, and clear the lease in the same statement.
-- ----------------------------------------------------------------------------

UPDATE outbox_events
SET available_at = clock_timestamp()
                  + make_interval(
                        secs => LEAST(
                            3600,
                            30 * power(2, LEAST(attempts, 7))::integer
                        )
                    ),
    locked_by = NULL,
    locked_until = NULL,
    last_error = 'simulated broker timeout'
WHERE locked_by = 'worker-1'
  AND published_at IS NULL
  AND dead_lettered_at IS NULL
RETURNING event_id, attempts, available_at, last_error;

-- Expected: events 3 and 4 are released with a future retry time.
-- Jitter (for example, a random factor around the backoff) is recommended in
-- production to prevent many workers retrying simultaneously.

-- ----------------------------------------------------------------------------
-- Q5. Move exhausted failures to a dead-letter state.
--
-- Problem:
-- Events that have reached five attempts and have a recorded failure must no
-- longer be claimed by normal workers. Preserve the payload for investigation.
--
-- Optimized solution:
-- Use a targeted UPDATE and retain the original event row as the DLQ record.
-- A separate archive table or topic can be used when retention requirements
-- demand it.
-- ----------------------------------------------------------------------------

UPDATE outbox_events
SET dead_lettered_at = clock_timestamp(),
    locked_by = NULL,
    locked_until = NULL
WHERE published_at IS NULL
  AND dead_lettered_at IS NULL
  AND attempts >= 5
  AND last_error IS NOT NULL
  AND locked_until IS NULL
RETURNING event_id, attempts, last_error, dead_lettered_at;

-- Expected: event 6 is dead-lettered. Event 7 was already in the DLQ.

-- ----------------------------------------------------------------------------
-- Q6. Make a consumer idempotent with an inbox key.
--
-- Problem:
-- A broker may redeliver event 1 after the consumer committed its database
-- work but before its acknowledgement reached the broker. Apply the event once.
--
-- Optimized solution:
-- Insert (consumer_name, event_id) into the inbox with ON CONFLICT DO NOTHING.
-- Only rows returned by that insert are allowed to mutate the projection.
-- Run the statement twice: the second execution must be a no-op.
-- ----------------------------------------------------------------------------

CREATE TABLE consumer_inbox (
    consumer_name text NOT NULL,
    event_id      bigint NOT NULL,
    processed_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (consumer_name, event_id)
);

CREATE TABLE order_projection (
    order_id      bigint PRIMARY KEY,
    status        text NOT NULL,
    total         numeric(12,2) NOT NULL,
    last_event_id bigint NOT NULL,
    updated_at    timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Execute this statement twice to simulate broker redelivery.
WITH accepted AS (
    INSERT INTO consumer_inbox (consumer_name, event_id)
    SELECT 'order-projection', e.event_id
    FROM outbox_events AS e
    WHERE e.event_id = 1
    ON CONFLICT (consumer_name, event_id) DO NOTHING
    RETURNING event_id
)
INSERT INTO order_projection (order_id, status, total, last_event_id)
SELECT
    (e.payload ->> 'order_id')::bigint,
    e.payload ->> 'status',
    (e.payload ->> 'total')::numeric,
    e.event_id
FROM outbox_events AS e
JOIN accepted AS a USING (event_id)
ON CONFLICT (order_id) DO UPDATE
SET status = EXCLUDED.status,
    total = EXCLUDED.total,
    last_event_id = EXCLUDED.last_event_id,
    updated_at = clock_timestamp()
WHERE EXCLUDED.last_event_id > order_projection.last_event_id;

-- Expected: the inbox contains one key for (order-projection, 1), even after
-- running the statement twice. A stale event cannot overwrite a newer version.

DO $$
BEGIN
    IF (
        SELECT count(*)
        FROM consumer_inbox
        WHERE consumer_name = 'order-projection'
          AND event_id = 1
    ) <> 1 THEN
        RAISE EXCEPTION 'Consumer inbox did not deduplicate event 1';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM order_projection
        WHERE order_id = 1001
          AND last_event_id = 1
          AND status = 'PLACED'
    ) THEN
        RAISE EXCEPTION 'Expected order 1001 projection was not applied';
    END IF;
END;
$$;

-- ----------------------------------------------------------------------------
-- Q7. Build an operational backlog and delivery-health snapshot.
--
-- Problem:
-- Return pending, ready, leased, retry-wait, dead-letter, and recently published
-- counts, plus the age of the oldest non-terminal event.
--
-- Optimized solution:
-- Use one scan with FILTER aggregates instead of repeatedly scanning the table
-- for separate dashboard cards.
-- ----------------------------------------------------------------------------

SELECT
    count(*) FILTER (
        WHERE published_at IS NULL AND dead_lettered_at IS NULL
    ) AS pending_events,
    count(*) FILTER (
        WHERE published_at IS NULL
          AND dead_lettered_at IS NULL
          AND available_at <= clock_timestamp()
          AND (locked_until IS NULL OR locked_until <= clock_timestamp())
    ) AS ready_events,
    count(*) FILTER (
        WHERE published_at IS NULL
          AND dead_lettered_at IS NULL
          AND locked_until > clock_timestamp()
    ) AS leased_events,
    count(*) FILTER (
        WHERE published_at IS NULL
          AND dead_lettered_at IS NULL
          AND available_at > clock_timestamp()
    ) AS retry_wait_events,
    count(*) FILTER (WHERE dead_lettered_at IS NOT NULL) AS dead_letter_events,
    count(*) FILTER (
        WHERE published_at >= clock_timestamp() - interval '1 hour'
    ) AS published_last_hour,
    round(
        extract(epoch FROM (
            clock_timestamp()
            - min(created_at) FILTER (
                WHERE published_at IS NULL AND dead_lettered_at IS NULL
            )
        ))::numeric,
        1
    ) AS oldest_pending_age_seconds
FROM outbox_events;

-- Production alert ideas:
-- * oldest_pending_age_seconds exceeds the event-delivery SLA;
-- * ready_events grows continuously while published_last_hour falls;
-- * expired leases increase, indicating worker crashes or undersized leases;
-- * dead_letter_events increases and needs an owned remediation workflow.

-- ----------------------------------------------------------------------------
-- Q8. Add claim/retention indexes and delete published history in small batches.
--
-- Problem:
-- Support the ordered claim query, find expired leases, and remove old published
-- events without a single large delete transaction.
--
-- Optimized solution:
-- Partial indexes exclude terminal rows from the hot claim path. The bounded
-- cleanup uses SKIP LOCKED so multiple maintenance workers can cooperate.
-- ----------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS ix_outbox_claim_order
    ON outbox_events (created_at, event_id)
    WHERE published_at IS NULL AND dead_lettered_at IS NULL;

CREATE INDEX IF NOT EXISTS ix_outbox_expired_lease
    ON outbox_events (locked_until)
    WHERE published_at IS NULL
      AND dead_lettered_at IS NULL
      AND locked_until IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_outbox_published_retention
    ON outbox_events (published_at, event_id)
    WHERE published_at IS NOT NULL;

-- Optional cleanup exercise. The sample is intentionally recent, so this
-- normally deletes zero rows. Change the interval only in a disposable copy.
WITH doomed AS (
    SELECT event_id
    FROM outbox_events
    WHERE published_at < clock_timestamp() - interval '30 days'
    ORDER BY published_at, event_id
    FOR UPDATE SKIP LOCKED
    LIMIT 1000
)
DELETE FROM outbox_events AS e
USING doomed AS d
WHERE e.event_id = d.event_id
RETURNING e.event_id;

