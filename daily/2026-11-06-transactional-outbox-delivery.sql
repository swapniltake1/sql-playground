Topic: Transactional Outbox, Concurrent Delivery, Retries & Idempotent Consumers
Dialect: PostgreSQL 14+

PROBLEM STATEMENT
A banking/order platform commits business changes to PostgreSQL and publishes
events to a message broker. A direct "write database, then publish" sequence can
lose events if the process crashes between the two operations. Implement the
transactional outbox pattern and the SQL used by concurrent publisher workers.

Run this file independently in a disposable PostgreSQL database. The setup is
repeatable because it recreates only the practice tables below.

KEY DELIVERY GUARANTEE
The outbox makes the business row and event row atomic in one database
transaction. A publisher can still publish an event more than once (for example,
if it crashes after broker acknowledgement but before marking the row published).
Consumers therefore need idempotency. This is normally at-least-once delivery,
not magical end-to-end exactly-once delivery.
===============================================================================
*/

