-- ============================================================================
-- 6. Practical performance and correctness notes
-- ============================================================================

-- 1. Canonicalization is a correctness boundary. If the source uses a composite
--    event identity, partition by every component (for example source_system
--    plus source_event_key), not by a key that is only locally unique.
-- 2. Resolve void/cancel versions after ranking. Filtering is_void before the
--    ranking can accidentally resurrect an older event that was later voided.
-- 3. Keep money in integer minor units and keep currency in the grouping key.
--    Never add amounts across currencies without an explicit FX conversion.
-- 4. Aggregate facts to their intended grain before joining one-to-many
--    dimensions or histories; otherwise claim totals can be multiplied.
-- 5. Use half-open effective periods consistently. Adjacent rows ending and
--    starting on the same date do not overlap under [from, to) semantics.
-- 6. A priority-selected treaty is only one possible contract rule. Real
--    reinsurance calculations may require multiple layers, annual aggregates,
--    reinstatements, exclusions, expenses and treaty-specific subject premium.
-- 7. Monthly snapshots are cumulative values. Summing them across development
--    months is not meaningful; compare periods or build a proper development
--    triangle with a consistent valuation basis.
-- 8. Validate indexes with representative row counts, skew, cache state and
--    write volume. Every additional index increases ingestion and maintenance
--    cost. Check actual versus estimated rows and buffer reads in query plans.
-- 9. For high-volume event histories, partition by a stable event-time or
--    ingestion-time key only after defining cross-partition replay identity,
--    retention and late-arrival handling.
-- 10. The seeded anomalies are intentional learning cases. Correct source
--     records and policy decisions in governed workflows; do not silently
--     delete financial evidence to make a report balance.

