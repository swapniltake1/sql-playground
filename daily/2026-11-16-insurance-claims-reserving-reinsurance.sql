-- ============================================================================
-- Q2. Validate policy and coverage eligibility on the date of loss.
--
-- Problem:
-- Classify every claim as covered, policy-out-of-force, or without matching
-- coverage. Use half-open effective dates [effective_from, effective_to).
--
-- Optimization:
-- Join on policy_id and exact loss_type, then apply simple date inequalities.
-- Avoid wrapping indexed date columns in DATE_TRUNC or CAST expressions.
-- ============================================================================

SELECT
    c.claim_number,
    c.loss_date,
    p.policy_number,
    c.loss_type,
    CASE
        WHEN p.policy_id IS NULL THEN 'MISSING_POLICY'
        WHEN c.loss_date < p.effective_from
          OR c.loss_date >= p.effective_to THEN 'POLICY_OUT_OF_FORCE'
        WHEN cv.coverage_id IS NULL THEN 'NO_MATCHING_COVERAGE'
        ELSE 'COVERED'
    END AS coverage_decision,
    cv.coverage_code,
    cv.limit_minor,
    cv.deductible_minor
FROM claim AS c
LEFT JOIN policy AS p
       ON p.policy_id = c.policy_id
LEFT JOIN coverage AS cv
       ON cv.policy_id = c.policy_id
      AND cv.loss_type = c.loss_type
      AND c.loss_date >= cv.effective_from
      AND c.loss_date <  cv.effective_to
ORDER BY c.claim_id;

