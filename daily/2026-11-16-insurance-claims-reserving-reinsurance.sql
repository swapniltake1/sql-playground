-- ============================================================================
-- Q7. Estimate an illustrative excess-of-loss recoverable per claim.
--
-- Problem:
-- Select the highest-priority treaty active on the loss date for the claim's
-- product and loss type. Calculate:
--   recoverable = MIN(MAX(gross_incurred - attachment, 0), treaty_limit)
--                 * cession_pct
--
-- Optimization:
-- Use LATERAL with a matching composite lookup and LIMIT 1. This prevents a
-- many-to-many join when treaty rows overlap. The priority rule is explicit.
--
-- Assumption:
-- This practice selects one treaty row per claim. It does not model stacked
-- layers, reinstatements, hours clauses, expenses, exclusions or aggregates.
-- ============================================================================

WITH financials AS (
    SELECT
        claim_id,
        COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'PAYMENT'), 0)
        + COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'RESERVE_DELTA'), 0)
            AS gross_incurred_minor
    FROM canonical_claim_events
    WHERE event_type IN ('PAYMENT', 'RESERVE_DELTA')
    GROUP BY claim_id
)
SELECT
    c.claim_number,
    COALESCE(f.gross_incurred_minor, 0) AS gross_incurred_minor,
    t.treaty_name,
    t.attachment_minor,
    t.limit_minor,
    t.cession_pct,
    CASE WHEN t.treaty_id IS NULL THEN 0
         ELSE ROUND(
             LEAST(
                 GREATEST(COALESCE(f.gross_incurred_minor, 0)
                          - t.attachment_minor, 0),
                 t.limit_minor
             ) * t.cession_pct
         )::bigint
    END AS estimated_recoverable_minor
FROM claim AS c
JOIN policy AS p USING (policy_id)
LEFT JOIN financials AS f USING (claim_id)
LEFT JOIN LATERAL (
    SELECT rt.*
    FROM reinsurance_treaty AS rt
    WHERE rt.product_code = p.product_code
      AND rt.loss_type = c.loss_type
      AND c.loss_date >= rt.valid_from
      AND c.loss_date <  rt.valid_to
    ORDER BY rt.priority DESC, rt.valid_from DESC, rt.treaty_id DESC
    LIMIT 1
) AS t ON true
ORDER BY c.claim_id;

-- Claims without a matching treaty return zero estimated recoverable.
-- For claim 1004 (30 June), both AUTO/COLLISION treaties are active; priority
-- 20 selects the midyear endorsement. Q8 exposes the overlap for governance.

-- ============================================================================
-- Q8. Detect overlapping effective-dated coverage and treaty records.
--
-- Problem:
-- Return pairs of records for the same policy/loss type or product/loss type
-- whose half-open validity periods overlap.
--
-- Optimization:
-- The self-join uses strict inequalities and id ordering to avoid duplicate
-- pairs and self-matches. For large histories, consider range types and GiST.
-- ============================================================================

SELECT
    'COVERAGE' AS entity_type,
    a.coverage_id::text AS record_a,
    b.coverage_id::text AS record_b,
    a.policy_id::text AS business_key,
    GREATEST(a.effective_from, b.effective_from) AS overlap_from,
    LEAST(a.effective_to, b.effective_to) AS overlap_to
FROM coverage AS a
JOIN coverage AS b
  ON b.policy_id = a.policy_id
 AND b.loss_type = a.loss_type
 AND b.coverage_id > a.coverage_id
 AND a.effective_from < b.effective_to
 AND b.effective_from < a.effective_to

UNION ALL

SELECT
    'TREATY' AS entity_type,
    a.treaty_id::text AS record_a,
    b.treaty_id::text AS record_b,
    a.product_code || '/' || a.loss_type AS business_key,
    GREATEST(a.valid_from, b.valid_from) AS overlap_from,
    LEAST(a.valid_to, b.valid_to) AS overlap_to
FROM reinsurance_treaty AS a
JOIN reinsurance_treaty AS b
  ON b.product_code = a.product_code
 AND b.loss_type = a.loss_type
 AND b.treaty_id > a.treaty_id
 AND a.valid_from < b.valid_to
 AND b.valid_from < a.valid_to
ORDER BY entity_type, business_key, overlap_from;

