-- ============================================================================
-- Q3. Find the adjuster responsible at a reporting cutoff.
--
-- Problem:
-- Return one row per claim and the adjuster assignment active at
-- 2026-11-16 23:59:59 UTC. Claims without an assignment must remain visible.
--
-- Optimization:
-- LATERAL ... ORDER BY ... LIMIT 1 performs a bounded lookup per claim when
-- supported by (claim_id, assigned_at DESC). It avoids ranking all history
-- rows when only the current assignment is required.
-- ============================================================================

SELECT
    c.claim_number,
    a.adjuster_id,
    a.assigned_at,
    a.unassigned_at
FROM claim AS c
LEFT JOIN LATERAL (
    SELECT aa.adjuster_id, aa.assigned_at, aa.unassigned_at
    FROM adjuster_assignment AS aa
    WHERE aa.claim_id = c.claim_id
      AND aa.assigned_at < TIMESTAMPTZ '2026-11-17 00:00:00+00'
      AND (aa.unassigned_at IS NULL
           OR aa.unassigned_at > TIMESTAMPTZ '2026-11-16 23:59:59+00')
    ORDER BY aa.assigned_at DESC, aa.assignment_id DESC
    LIMIT 1
) AS a ON true
ORDER BY c.claim_id;

-- ============================================================================
-- Q4. Reconstruct paid, outstanding reserve, recovery and net incurred.
--
-- Problem:
-- Aggregate the canonical event ledger at claim grain:
--   paid             = SUM(PAYMENT)
--   outstanding      = SUM(RESERVE_DELTA)
--   recoveries       = SUM(RECOVERY)
--   gross incurred   = paid + outstanding
--   net incurred     = gross incurred - recoveries
--
-- Optimization:
-- Filtered aggregates scan the canonical event stream once rather than
-- joining three separately aggregated event subsets. Aggregate before
-- joining claim dimensions to preserve one row per claim.
-- ============================================================================

WITH financials AS (
    SELECT
        claim_id,
        COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'PAYMENT'), 0) AS paid_minor,
        COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'RESERVE_DELTA'), 0) AS reserve_minor,
        COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'RECOVERY'), 0) AS recovery_minor
    FROM canonical_claim_events
    WHERE event_type IN ('PAYMENT', 'RESERVE_DELTA', 'RECOVERY')
    GROUP BY claim_id
)
SELECT
    c.claim_number,
    COALESCE(f.paid_minor, 0) AS paid_minor,
    COALESCE(f.reserve_minor, 0) AS outstanding_reserve_minor,
    COALESCE(f.recovery_minor, 0) AS recovery_minor,
    COALESCE(f.paid_minor, 0) + COALESCE(f.reserve_minor, 0)
        AS gross_incurred_minor,
    COALESCE(f.paid_minor, 0) + COALESCE(f.reserve_minor, 0)
        - COALESCE(f.recovery_minor, 0) AS net_incurred_minor
FROM claim AS c
LEFT JOIN financials AS f USING (claim_id)
ORDER BY c.claim_id;

