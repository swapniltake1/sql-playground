-- ============================================================================
-- Q1. Canonicalize replayed and corrected claim-financial events.
--
-- Problem:
-- Return one current version per source_event_key. A voided latest version
-- cancels the logical event; do not fall back to an older non-void version.
--
-- Optimization:
-- Rank only by the logical event key and deterministic version/arrival keys.
-- Keep the landing data immutable; downstream consumers read this view.
-- ============================================================================

CREATE OR REPLACE VIEW canonical_claim_events AS
SELECT event_id, claim_id, source_event_key, source_version, event_type,
       amount_minor, is_void, occurred_at, ingested_at
FROM (
    SELECT e.*,
           ROW_NUMBER() OVER (
               PARTITION BY source_event_key
               ORDER BY source_version DESC, ingested_at DESC, event_id DESC
           ) AS rn
    FROM claim_event_landing AS e
) AS ranked
WHERE rn = 1
  AND is_void = false;

