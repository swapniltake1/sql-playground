CREATE TABLE policy (
    policy_id           bigint PRIMARY KEY,
    policy_number       text NOT NULL UNIQUE,
    product_code        text NOT NULL,
    currency_code       char(3) NOT NULL,
    effective_from      date NOT NULL,
    effective_to        date NOT NULL,
    policy_limit_minor  bigint NOT NULL CHECK (policy_limit_minor >= 0),
    deductible_minor    bigint NOT NULL CHECK (deductible_minor >= 0),
    CHECK (effective_to > effective_from)
);

CREATE TABLE coverage (
    coverage_id         bigint PRIMARY KEY,
    policy_id           bigint NOT NULL REFERENCES policy(policy_id),
    coverage_code       text NOT NULL,
    loss_type           text NOT NULL,
    effective_from      date NOT NULL,
    effective_to        date NOT NULL,
    limit_minor         bigint NOT NULL CHECK (limit_minor >= 0),
    deductible_minor    bigint NOT NULL CHECK (deductible_minor >= 0),
    CHECK (effective_to > effective_from)
);

CREATE TABLE claim (
    claim_id                bigint PRIMARY KEY,
    claim_number            text NOT NULL UNIQUE,
    policy_id               bigint NOT NULL REFERENCES policy(policy_id),
    loss_date               date NOT NULL,
    reported_at             timestamptz NOT NULL,
    loss_type               text NOT NULL,
    claim_status            text NOT NULL CHECK (claim_status IN
                              ('OPEN', 'CLOSED', 'REOPENED')),
    reported_loss_minor     bigint NOT NULL CHECK (reported_loss_minor >= 0),
    currency_code           char(3) NOT NULL
);

-- Landing table intentionally permits replayed versions and orphan claim IDs.
-- source_event_key identifies one logical event; source_version supersedes it.
-- RESERVE_DELTA may be positive or negative. PAYMENT and RECOVERY should be >= 0.
CREATE TABLE claim_event_landing (
    event_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id            bigint NOT NULL,
    source_event_key    text NOT NULL,
    source_version      integer NOT NULL CHECK (source_version > 0),
    event_type          text NOT NULL CHECK (event_type IN
                          ('RESERVE_DELTA', 'PAYMENT', 'RECOVERY', 'STATUS')),
    amount_minor        bigint NOT NULL DEFAULT 0,
    is_void             boolean NOT NULL DEFAULT false,
    occurred_at         timestamptz NOT NULL,
    ingested_at         timestamptz NOT NULL
);

CREATE TABLE adjuster_assignment (
    assignment_id      bigint PRIMARY KEY,
    claim_id           bigint NOT NULL REFERENCES claim(claim_id),
    adjuster_id        text NOT NULL,
    assigned_at        timestamptz NOT NULL,
    unassigned_at      timestamptz,
    CHECK (unassigned_at IS NULL OR unassigned_at > assigned_at)
);

-- Monthly cumulative snapshots can also be replayed or corrected.
CREATE TABLE claim_monthly_snapshot (
    snapshot_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id               bigint NOT NULL,
    snapshot_month         date NOT NULL,
    source_version         integer NOT NULL CHECK (source_version > 0),
    case_reserve_minor     bigint NOT NULL,
    cumulative_paid_minor  bigint NOT NULL,
    captured_at            timestamptz NOT NULL
);

CREATE TABLE reinsurance_treaty (
    treaty_id           bigint PRIMARY KEY,
    treaty_name         text NOT NULL,
    product_code        text NOT NULL,
    loss_type           text NOT NULL,
    valid_from          date NOT NULL,
    valid_to            date NOT NULL,
    attachment_minor   bigint NOT NULL CHECK (attachment_minor >= 0),
    limit_minor         bigint NOT NULL CHECK (limit_minor >= 0),
    cession_pct         numeric(7,6) NOT NULL CHECK
                         (cession_pct >= 0 AND cession_pct <= 1),
    priority            integer NOT NULL,
    CHECK (valid_to > valid_from)
);

