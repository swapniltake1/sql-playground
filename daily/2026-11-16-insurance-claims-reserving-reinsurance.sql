-- ============================================================================
-- Q9. Report notification delay and open-claim aging by product.
--
-- Problem:
-- For claims reported during calendar 2026, calculate days from loss to
-- notification and summarize open-claim aging by product.
--
-- Optimization:
-- Filter the raw timestamptz column with a half-open UTC range. Avoid
-- DATE(reported_at) in the WHERE clause so a normal timestamp index can help.
-- ============================================================================

SELECT
    p.product_code,
    COUNT(*) AS reported_claims,
    ROUND(AVG(c.reported_at::date - c.loss_date), 2)
        AS avg_notification_delay_days,
    MAX(c.reported_at::date - c.loss_date)
        AS max_notification_delay_days,
    COUNT(*) FILTER (WHERE c.claim_status = 'OPEN') AS open_claims,
    ROUND(AVG(DATE '2026-11-16' - c.loss_date)
        FILTER (WHERE c.claim_status IN ('OPEN', 'REOPENED')), 2)
        AS avg_open_claim_age_days
FROM claim AS c
JOIN policy AS p USING (policy_id)
WHERE c.reported_at >= TIMESTAMPTZ '2026-01-01 00:00:00+00'
  AND c.reported_at <  TIMESTAMPTZ '2027-01-01 00:00:00+00'
GROUP BY p.product_code
ORDER BY p.product_code;

-- This sample intentionally includes late notifications and a reopened claim.
-- Operational SLA thresholds should be stored as configurable product/claim
-- rules rather than hard-coded into a production report.

-- ============================================================================
-- Q10. Produce a consolidated claim-ledger and snapshot exception feed.
--
-- Problem:
-- Find orphan financial events, orphan monthly snapshots, negative reserve
-- balances, negative payment/recovery events, negative snapshot reserves,
-- and claims with no financial activity.
--
-- Optimization:
-- Reuse canonicalized inputs and aggregate once per claim. UNION ALL preserves
-- independent exceptions and avoids the unnecessary sort/deduplication cost
-- of UNION. Entity keys are text so heterogeneous records share one output.
-- ============================================================================

WITH reserve_balance AS (
    SELECT claim_id, SUM(amount_minor) AS reserve_minor
    FROM canonical_claim_events
    WHERE event_type = 'RESERVE_DELTA'
    GROUP BY claim_id
),
financial_activity AS (
    SELECT DISTINCT claim_id
    FROM canonical_claim_events
    WHERE event_type IN ('RESERVE_DELTA', 'PAYMENT', 'RECOVERY')
),
ranked_snapshots AS (
    SELECT
        s.*,
        ROW_NUMBER() OVER (
            PARTITION BY claim_id, snapshot_month
            ORDER BY source_version DESC, captured_at DESC, snapshot_id DESC
        ) AS rn
    FROM claim_monthly_snapshot AS s
),
canonical_snapshots AS (
    SELECT *
    FROM ranked_snapshots
    WHERE rn = 1
)
SELECT
    'ORPHAN_CLAIM_EVENT' AS issue_code,
    e.source_event_key AS entity_key,
    'No matching claim master row' AS detail
FROM canonical_claim_events AS e
LEFT JOIN claim AS c USING (claim_id)
WHERE c.claim_id IS NULL

UNION ALL

SELECT
    'ORPHAN_MONTHLY_SNAPSHOT',
    s.claim_id::text || '/' || s.snapshot_month::text,
    'Snapshot has no matching claim master row'
FROM canonical_snapshots AS s
LEFT JOIN claim AS c USING (claim_id)
WHERE c.claim_id IS NULL

UNION ALL

SELECT
    'NEGATIVE_CASE_RESERVE',
    rb.claim_id::text,
    'Canonical reserve movement balance is below zero: ' || rb.reserve_minor
FROM reserve_balance AS rb
JOIN claim AS c USING (claim_id)
WHERE rb.reserve_minor < 0

UNION ALL

SELECT
    'NEGATIVE_CASH_EVENT',
    e.source_event_key,
    e.event_type || ' has negative amount_minor=' || e.amount_minor
FROM canonical_claim_events AS e
WHERE e.event_type IN ('PAYMENT', 'RECOVERY')
  AND e.amount_minor < 0

UNION ALL

SELECT
    'NEGATIVE_SNAPSHOT_RESERVE',
    s.claim_id::text || '/' || s.snapshot_month::text,
    'Case reserve is below zero: ' || s.case_reserve_minor
FROM canonical_snapshots AS s
WHERE s.case_reserve_minor < 0

UNION ALL

SELECT
    'CLAIM_WITHOUT_FINANCIAL_ACTIVITY',
    c.claim_number,
    'No canonical reserve, payment or recovery event'
FROM claim AS c
LEFT JOIN financial_activity AS fa USING (claim_id)
WHERE fa.claim_id IS NULL
ORDER BY issue_code, entity_key;

