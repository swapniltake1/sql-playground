-- ============================================================================
-- Q5. Rank large losses and calculate cumulative product concentration.
--
-- Problem:
-- Rank claims by gross incurred within product, attach the current adjuster,
-- and calculate each claim's cumulative share of product gross incurred.
--
-- Optimization:
-- Build one financial row per claim before windowing. The window operates on
-- the reduced claim grain, not on raw event rows. Use a deterministic claim_id
-- tie-breaker so rankings remain stable across executions.
-- ============================================================================

WITH financials AS (
    SELECT
        claim_id,
        COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'PAYMENT'), 0)
        + COALESCE(SUM(amount_minor)
            FILTER (WHERE event_type = 'RESERVE_DELTA'), 0)
            AS gross_incurred_minor
    FROM canonical_claim_events
    WHERE event_type IN ('PAYMENT', 'RESERVE_DELTA')
    GROUP BY claim_id
),
claim_grain AS (
    SELECT
        c.claim_id,
        c.claim_number,
        p.product_code,
        COALESCE(f.gross_incurred_minor, 0) AS gross_incurred_minor
    FROM claim AS c
    JOIN policy AS p USING (policy_id)
    LEFT JOIN financials AS f USING (claim_id)
    WHERE COALESCE(f.gross_incurred_minor, 0) >= 0
),
ranked AS (
    SELECT
        cg.*,
        ROW_NUMBER() OVER (
            PARTITION BY product_code
            ORDER BY gross_incurred_minor DESC, claim_id
        ) AS product_rank,
        SUM(gross_incurred_minor) OVER (
            PARTITION BY product_code
        ) AS product_total_minor,
        SUM(gross_incurred_minor) OVER (
            PARTITION BY product_code
            ORDER BY gross_incurred_minor DESC, claim_id
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS cumulative_incurred_minor
    FROM claim_grain AS cg
)
SELECT
    r.product_code,
    r.claim_number,
    a.adjuster_id,
    r.gross_incurred_minor,
    r.product_rank,
    ROUND(
        100.0 * r.cumulative_incurred_minor
        / NULLIF(r.product_total_minor, 0), 2
    ) AS cumulative_product_share_pct
FROM ranked AS r
LEFT JOIN LATERAL (
    SELECT aa.adjuster_id
    FROM adjuster_assignment AS aa
    WHERE aa.claim_id = r.claim_id
      AND aa.assigned_at < TIMESTAMPTZ '2026-11-17 00:00:00+00'
      AND (aa.unassigned_at IS NULL
           OR aa.unassigned_at > TIMESTAMPTZ '2026-11-16 23:59:59+00')
    ORDER BY aa.assigned_at DESC, aa.assignment_id DESC
    LIMIT 1
) AS a ON true
ORDER BY r.product_code, r.product_rank;

-- ============================================================================
-- Q6. Build an accident-quarter / development-month reserve triangle.
--
-- Problem:
-- Canonicalize monthly snapshots by claim and snapshot_month, then summarize
-- cumulative paid and case reserve by accident quarter and development month.
--
-- Optimization:
-- Deduplicate snapshots before aggregation. The month offset is calculated
-- from date parts, avoiding row-by-row AGE() interval formatting. The input
-- is reduced to one snapshot per claim-month before the triangle aggregation.
-- ============================================================================

WITH ranked_snapshots AS (
    SELECT
        s.*,
        ROW_NUMBER() OVER (
            PARTITION BY claim_id, snapshot_month
            ORDER BY source_version DESC, captured_at DESC, snapshot_id DESC
        ) AS rn
    FROM claim_monthly_snapshot AS s
),
canonical_snapshots AS (
    SELECT *
    FROM ranked_snapshots
    WHERE rn = 1
),
development AS (
    SELECT
        DATE_TRUNC('quarter', c.loss_date)::date AS accident_quarter,
        (
            (EXTRACT(YEAR FROM s.snapshot_month)::int
             - EXTRACT(YEAR FROM c.loss_date)::int) * 12
            + EXTRACT(MONTH FROM s.snapshot_month)::int
            - EXTRACT(MONTH FROM c.loss_date)::int
        ) AS development_month,
        s.cumulative_paid_minor,
        s.case_reserve_minor
    FROM canonical_snapshots AS s
    JOIN claim AS c USING (claim_id)
    WHERE s.snapshot_month >= DATE_TRUNC('month', c.loss_date)::date
)
SELECT
    accident_quarter,
    development_month,
    SUM(cumulative_paid_minor) AS cumulative_paid_minor,
    SUM(case_reserve_minor) AS case_reserve_minor,
    SUM(cumulative_paid_minor + case_reserve_minor) AS cumulative_incurred_minor
FROM development
GROUP BY accident_quarter, development_month
ORDER BY accident_quarter, development_month;

